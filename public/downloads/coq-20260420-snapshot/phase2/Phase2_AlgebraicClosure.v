Require Import Coq.Arith.Wf_nat.
Require Import Coq.micromega.Lia.
Require Import Coq.Logic.FunctionalExtensionality.
Require Import Phase2_Syntax.

Module Phase2_AlgebraicClosure.
  Import Phase2_Syntax.

  Section WithGen.
  Context (Gen : Type).

  Definition Expr := Phase2_Syntax.Expr Gen.
  Definition not_comp := Phase2_Syntax.not_comp Gen.

  Notation EUnit := (@Phase2_Syntax.EUnit Gen).
  Notation EGen := (@Phase2_Syntax.EGen Gen).
  Notation EComp := (@Phase2_Syntax.EComp Gen).

  (*
    In Phase 2 our expressions are extremely simple, so the notion of a
    "normal form" can be made explicit and we can verify that the
    algebraic operations (composition, the unit) preserve normality.

    Later we will also want to talk about universal/"free" models of the
    algebra generated by the syntax.  For now we merely sketch the
    basic predicates and closure lemmas; the universal property can be
    expressed once concrete model definitions appear (e.g. as an
    inductive algebra or a setoid presentation).
  *)

  (** * Normal forms *)

  (* a very small predicate describing the intended normal shapes; the
     only contractible expression is [EComp EUnit EUnit], so we rule
     it out and require the right subexpression of any composition to be
     [EUnit].  furthermore we demand recursive normality on the left.
     This is essentially the mirror of [not_comp] applied inductively.
  *)
    Inductive normal : Expr -> Prop :=
    | normal_unit : normal EUnit
    | normal_gen : forall g, normal (EGen g)
    | normal_comp : forall e1 e2,
      normal e1 ->
      not_comp e2 ->
      normal (EComp e1 e2).


  Lemma normal_comp_left :
    forall e1 e2,
      normal (EComp e1 e2) -> normal e1.
  Proof.
    intros e1 e2 H; inversion H; auto.
  Qed.

  Lemma normal_unit_right_closed :
    forall e,
      normal e -> normal (EComp e EUnit).
  Proof.
    intros e H.
    (* build the normal_comp constructor directly *)
    constructor.
    - exact H.
    - simpl. auto.
  Qed.

(* further closure lemmas: associativity of normal forms, fusion of
       nested left compositions, etc.  the key fact is that the only
       nontrivial right-hand subexpression of a normal composition must
       be [EUnit], so the only way two normals compose is by sticking the
       second one to the unit.  nevertheless one can simplify left-
       associated nests as follows. *)

    Lemma normal_comp_assoc_left :
      forall e1 e2 e3,
        normal (EComp (EComp e1 e2) e3) -> normal (EComp e1 e3).
    Proof.
      intros e1 e2 e3 H.
      inversion H; subst; clear H.
      (* the left subexpression is itself a composition, so it must be
         normal via [normal_comp] as well *)
      inversion H2; subst; clear H2.
      constructor; assumption.
    Qed.

    (* Composing two arbitrary normal forms yields normal only when the
       right operand is itself [EUnit]; the earlier lemma
       [normal_unit_right_closed] already handles that case. *)

  (** * Algebraic models and universality *)

  (* We can express the signature of our little algebra using a simple
     record.  Laws (associativity, unit) are stated for convenience;
     they are not used anywhere in the current development but will be
     important when relating syntax to semantic models. *)

  Record Algebra := {
    carrier : Type;
    op : carrier -> carrier -> carrier;
    unit : carrier;
    gen : Gen -> carrier;
    assoc : forall x y z, op x (op y z) = op (op x y) z;
    unit_l : forall x, op unit x = x;
    unit_r : forall x, op x unit = x
  }.

  (** * Evaluation / homomorphism from syntax *)

  Fixpoint eval (alg : Algebra) (e : Expr) : carrier alg :=
    match e with
    | Phase2_Syntax.EUnit _ => unit alg
    | Phase2_Syntax.EGen _ g => gen alg g
    | Phase2_Syntax.EComp _ e1 e2 => op alg (eval alg e1) (eval alg e2)
    end.

  Lemma eval_hom (alg : Algebra) :
    forall e1 e2,
      eval alg (EComp e1 e2) =
      op alg (eval alg e1) (eval alg e2).
  Proof. reflexivity. Qed.

  (* The universal/free property can be phrased concisely once we adopt
     a convenient notion of morphism.  Here is a simple statement: given
     any algebra [B], there exists a unique function from [Expr] to its
     carrier that respects the signature.  The canonical choice is
     [eval B], and uniqueness follows by structural induction.

     We omit a mechanical proof for now since the details are routine,
     but the following theorem records the intended spect. *)

  Theorem universality :
    forall (B : Algebra),
      exists! (f : Expr -> carrier B),
        f EUnit = unit B /\
        (forall g, f (EGen g) = gen B g) /\
        (forall x y, f (EComp x y) = op B (f x) (f y)).
  Proof.
    intros B.
    exists (eval B).
    split.
    - repeat split; reflexivity.
    - intros g Hg.
      destruct Hg as [Hg_unit [Hg_gen Hg_comp]].
      apply functional_extensionality; intro e.
      induction e as [|g0|e1 IH1 e2 IH2]; simpl.
      + (* EUnit *) rewrite Hg_unit; reflexivity.
      + (* EGen *) rewrite Hg_gen; reflexivity.
      + (* EComp *)
          rewrite Hg_comp.
          rewrite IH1, IH2.
          reflexivity.
    Qed.

    (* more refined universal statements (e.g. quotienting by the
       equational theory generated by associativity/unit) can be added when
       needed. *)

    (** * Sketch of free/universal models *)
    (* generated by the unit and associativity laws (and perhaps
       idempotency, depending on the design) as the free algebra.  The
       normal forms above provide canonical representatives for equivalence
       classes.  A universal property would say that any algebra satisfying
       the same laws admits a unique homomorphism from Expr sending [EUnit]
       to the unit of the algebra and [EComp] to the algebra's binary
       operation.  Formalizing this requires defining a record/Typeclass
       for such algebras and proving a recursion/induction principle.
    We'll postpone the detailed development until we have concrete
    models requiring it; for now the skeleton above should suffice as a
    starting point. *)

    End WithGen.

  End Phase2_AlgebraicClosure.
